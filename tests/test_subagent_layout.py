def _parse_yaml_frontmatter(text: str) -> "tuple[dict[str, str], str]":
    """Minimal strict parser for our generated single-line YAML frontmatter."""
    lines = text.splitlines()
    assert lines and lines[0] == "---", f"frontmatter must start on line 1: {lines[:2]!r}"
    end = None
    for idx in range(1, len(lines)):
        if lines[idx] == "---":
            end = idx
            break
    assert end is not None, "missing closing --- frontmatter fence"
    data: dict[str, str] = {}
    for line in lines[1:end]:
        assert ":" in line, f"invalid frontmatter line: {line!r}"
        key, raw_val = line.split(":", 1)
        key = key.strip()
        val = raw_val.strip()
        if val.startswith('"') and val.endswith('"'):
            import json

            val = json.loads(val)
        data[key] = val
    body = "\n".join(lines[end + 1 :])
    return data, body


def _run_cli(*args: str, cwd: "Path | None" = None, env: "dict[str, str] | None" = None):
    merged_env = os.environ.copy()
    merged_env["BOBP_NO_VERSION_CHECK"] = "1"
    if env:
        merged_env.update(env)
    return subprocess.run(
        [sys.executable, "-m", "bobp.cli", *args],
        cwd=cwd,
        env=merged_env,
        capture_output=True,
        text=True,
    )


class TestSubagentCompilation(unittest.TestCase):
    def setUp(self) -> None:
        self.tmpl = _bob_manage.templates_dir()

    def test_compile_generates_30_valid_subagents_for_10_personas_only(self) -> None:
        expected_personas = sorted(_skill_layout.persona_names(self.tmpl))
        self.assertEqual(len(expected_personas), 10)

        compiled = _subagent_layout.compile_subagents(self.tmpl)
        self.assertEqual(len(compiled), 30)

        rel_paths = sorted(compiled.keys())
        for name in expected_personas:
            self.assertIn(f".claude/agents/{name}.md", rel_paths)
            self.assertIn(f".codex/agents/{name}.toml", rel_paths)
            self.assertIn(f".gemini/agents/{name}.md", rel_paths)

        # Shared workflow skills must NOT appear in harness subagent dirs.
        for shared in ("make", "sprint", "chat", "bob-tools", "impl"):
            for harness_dir, ext in _subagent_layout.HARNESS_SPECS.values():
                self.assertNotIn(f"{harness_dir}/{shared}{ext}", compiled)

        for rel, content in compiled.items():
            persona = Path(rel).stem
            shared_state_marker = f"agents/{persona}/state.md"
            if rel.startswith(".claude/agents/"):
                fm, body = _parse_yaml_frontmatter(content)
                self.assertEqual(set(fm.keys()), {"name", "description"})
                self.assertEqual(fm["name"], persona)
                self.assertTrue(fm["description"].strip())
                self.assertNotIn("memory", fm)
                self.assertNotIn("model", fm)
                self.assertNotIn("tools", fm)
                self.assertIn("Generated by bobp from", body[:250])
                self.assertIn(shared_state_marker, body[:500])
                self.assertIn("agents/CHAT.md", body[:500])
            elif rel.startswith(".gemini/agents/"):
                fm, body = _parse_yaml_frontmatter(content)
                self.assertEqual(set(fm.keys()), {"name", "description", "kind"})
                self.assertEqual(fm["name"], persona)
                self.assertEqual(fm["kind"], "local")
                self.assertTrue(fm["description"].strip())
                self.assertNotIn("model", fm)
                self.assertNotIn("tools", fm)
                self.assertIn("Generated by bobp from", body[:250])
                self.assertIn(shared_state_marker, body[:500])
                self.assertIn("agents/CHAT.md", body[:500])
            elif rel.startswith(".codex/agents/"):
                self.assertTrue(content.startswith("# Generated by bobp from "))
                if tomllib is not None:
                    parsed = tomllib.loads(content)
                    self.assertEqual(
                        set(parsed.keys()), {"name", "description", "developer_instructions"}
                    )
                    self.assertEqual(parsed["name"], persona)
                    self.assertTrue(parsed["description"].strip())
                    self.assertNotIn("model", parsed)
                    self.assertNotIn("sandbox_mode", parsed)
                    instr = parsed["developer_instructions"]
                    self.assertIn(shared_state_marker, instr[:400])
                    self.assertIn("agents/CHAT.md", instr[:400])

    def test_adversarial_yaml_and_toml_escaping_round_trips(self) -> None:
        desc = 'Use when: #tricky "quoted"\nmodel: opus\n---\r\x00\x1b\x7f'
        body = (
            'Intro with """triple""", """"quad"""", """"""six""""""\n'
            'Pipe escape \\| and trailing backslash \\\n'
            'Control chars \x00 \x1b \x7f and CR\r\n'
            'Ends with quote"'
        )
        claude_md = _subagent_layout.render_claude("neo", desc, body)
        fm, claude_body = _parse_yaml_frontmatter(claude_md)
        self.assertEqual(set(fm.keys()), {"name", "description"})
        self.assertEqual(fm["name"], "neo")
        self.assertNotIn("\n", claude_md.splitlines()[2])
        self.assertEqual(fm["description"], desc)
        self.assertIn('Ends with quote"', claude_body)

        gemini_md = _subagent_layout.render_gemini("neo", desc, body)
        g_fm, _ = _parse_yaml_frontmatter(gemini_md)
        self.assertEqual(set(g_fm.keys()), {"name", "description", "kind"})
        self.assertEqual(g_fm["kind"], "local")
        self.assertEqual(g_fm["description"], desc)

        codex_toml = _subagent_layout.render_codex("neo", desc, body)
        if tomllib is not None:
            parsed = tomllib.loads(codex_toml)
            self.assertEqual(parsed["name"], "neo")
            self.assertEqual(parsed["description"], desc)
            expected_body_norm = body.replace("\r\n", "\n").replace("\r", "\n")
            self.assertIn(expected_body_norm, parsed["developer_instructions"])

    def test_frontmatter_parser_rejects_mismatched_name_and_empty_description(self) -> None:
        with self.assertRaises(ValueError):
            _subagent_layout.parse_persona_skill(
                "---\nname: other\ndescription: valid\n---\nBody\n", expected_name="neo"
            )
        with self.assertRaises(ValueError):
            _subagent_layout.parse_persona_skill(
                "---\nname: neo\ndescription:   \n---\nBody\n", expected_name="neo"
            )

    def test_linear_time_on_50k_hostile_frontmatter_and_manifest(self) -> None:
        def _timeout(_signum, _frame):
            raise TimeoutError("non-linear parser stall")

        prev = signal.signal(signal.SIGALRM, _timeout)
        signal.alarm(3)
        try:
            hostile_skill = "---\n" + ("a" * 50_000) + "\n"
            with self.assertRaises(ValueError):
                _subagent_layout.parse_persona_skill(hostile_skill, expected_name="neo")

            for line in ("a" * 50_000, ".claude/agents/" + ("a" * 50_000) + ".md"):
                self.assertFalse(_subagent_layout.valid_subagent_relpath(line))
        finally:
            signal.alarm(0)
            signal.signal(signal.SIGALRM, prev)


class TestSubagentFilesystemAndSafety(unittest.TestCase):
    def setUp(self) -> None:
        self.tmpl = _bob_manage.templates_dir()

    def _tmp_project(self, name: str) -> Path:
        base = Path("build/pytest/subagent_tests").resolve() / name
        if base.exists():
            import shutil

            shutil.rmtree(base)
        base.mkdir(parents=True)
        return base

    def test_place_subagents_preserves_custom_files_and_tracks_manifest(self) -> None:
        proj = self._tmp_project("custom_preserve")
        (proj / "agents").mkdir()
        (proj / ".claude" / "agents").mkdir(parents=True)
        custom = proj / ".claude" / "agents" / "neo.md"
        custom.write_text("USER CUSTOM NEO\n", encoding="utf-8")
        extra = proj / ".codex" / "agents"
        extra.mkdir(parents=True)
        (extra / "my-helper.toml").write_text('name = "my-helper"\n', encoding="utf-8")

        actions = _subagent_layout.place_subagents(proj, self.tmpl)
        skipped = [a for a in actions if a.kind == "skipped"]
        self.assertEqual([a.path for a in skipped], [".claude/agents/neo.md"])
        self.assertEqual(custom.read_text(encoding="utf-8"), "USER CUSTOM NEO\n")
        self.assertTrue((extra / "my-helper.toml").is_file())

        owned = _subagent_layout.read_manifest(proj)
        self.assertEqual(len(owned), 29)
        self.assertNotIn(".claude/agents/neo.md", owned)
        self.assertIn(".codex/agents/neo.toml", owned)
        self.assertIn(".gemini/agents/neo.md", owned)

        # Second run refreshes owned 29, still skips user's neo.md, creates 0 symlinks.
        actions2 = _subagent_layout.place_subagents(proj, self.tmpl)
        self.assertEqual(sum(1 for a in actions2 if a.kind == "replace"), 29)
        self.assertEqual(sum(1 for a in actions2 if a.kind == "skipped"), 1)
        self.assertEqual(custom.read_text(encoding="utf-8"), "USER CUSTOM NEO\n")
        symlinks = [p for p in proj.rglob("*") if p.is_symlink()]
        self.assertEqual(symlinks, [])

    def test_preflight_refuses_symlinked_parents_and_manifest_with_zero_partial_writes(self) -> None:
        cases = [
            "agents",
            ".claude",
            ".claude/agents",
            ".codex",
            ".codex/agents",
            ".gemini",
            ".gemini/agents",
            "agents/.bobp-subagents",
        ]
        for hostile_rel in cases:
            with self.subTest(hostile=hostile_rel):
                proj = self._tmp_project(f"hostile_{hostile_rel.replace('/', '_').replace('.', '')}")
                outside = proj.parent / f"outside_{proj.name}"
                outside.mkdir(exist_ok=True)
                target = proj / hostile_rel
                if target.parent != proj:
                    target.parent.mkdir(parents=True, exist_ok=True)
                target.symlink_to(outside)

                with self.assertRaises(_subagent_layout.SubagentLayoutError):
                    _subagent_layout.place_subagents(proj, self.tmpl)

                # Zero partial writes in sibling harness dirs.
                for hdir in (".claude/agents", ".codex/agents", ".gemini/agents"):
                    p = proj / hdir
                    if hdir != hostile_rel and p.exists() and not p.is_symlink():
                        self.assertEqual(list(p.iterdir()), [])

    def test_fifo_at_manifest_target_or_gitignore_never_blocks(self) -> None:
        if not hasattr(os, "mkfifo"):
            self.skipTest("mkfifo unavailable")

        def _timeout(_signum, _frame):
            raise TimeoutError("blocked on FIFO")

        prev = signal.signal(signal.SIGALRM, _timeout)
        signal.alarm(5)
        try:
            # 1. FIFO at manifest refuses cleanly in pre-flight.
            proj1 = self._tmp_project("fifo_manifest")
            (proj1 / "agents").mkdir()
            os.mkfifo(proj1 / "agents" / _subagent_layout.MANIFEST_NAME)
            with self.assertRaises(_subagent_layout.SubagentLayoutError):
                _subagent_layout.place_subagents(proj1, self.tmpl)

            # 2. FIFO at target subagent file is skipped without blocking.
            proj2 = self._tmp_project("fifo_target")
            (proj2 / "agents").mkdir()
            (proj2 / ".claude" / "agents").mkdir(parents=True)
            os.mkfifo(proj2 / ".claude" / "agents" / "neo.md")
            actions = _subagent_layout.place_subagents(proj2, self.tmpl)
            skipped = [a for a in actions if a.path == ".claude/agents/neo.md"]
            self.assertEqual(len(skipped), 1)
            self.assertEqual(skipped[0].kind, "skipped")

            # 3. FIFO at .gitignore does not block.
            os.mkfifo(proj2 / ".gitignore")
            self.assertEqual(_subagent_layout.gitignore_hides_subagents(proj2), [])
        finally:
            signal.alarm(0)
            signal.signal(signal.SIGALRM, prev)

    def test_oversized_manifest_fails_closed(self) -> None:
        proj = self._tmp_project("oversize_manifest")
        (proj / "agents").mkdir()
        (proj / "agents" / _subagent_layout.MANIFEST_NAME).write_text(
            ".claude/agents/neo.md\n" * 4000, encoding="utf-8"
        )
        self.assertEqual(_subagent_layout.read_manifest(proj), set())

    def test_gitignore_hides_subagents_respects_git_negation_semantics(self) -> None:
        proj = self._tmp_project("gitignore_negation")
        gi = proj / ".gitignore"

        # Wholesale .claude hides .claude/agents/ even if negated!
        gi.write_text(".claude\n!.claude/agents/\n", encoding="utf-8")
        self.assertEqual(_subagent_layout.gitignore_hides_subagents(proj), [".claude/agents/"])

        # Allowlist .claude/* + !.claude/agents/ does NOT hide .claude/agents/.
        gi.write_text(".claude/*\n!.claude/agents/\n", encoding="utf-8")
        self.assertEqual(_subagent_layout.gitignore_hides_subagents(proj), [])

        # .claude/* without negation hides it, plus .codex/ and .gemini/**.
        gi.write_text(".claude/*\n.codex/\n.gemini/**\n", encoding="utf-8")
        self.assertEqual(
            _subagent_layout.gitignore_hides_subagents(proj),
            [".claude/agents/", ".codex/agents/", ".gemini/agents/"],
        )

    def test_control_chars_sanitized_in_error_and_summary(self) -> None:
        evil = "evil\x1b[31m\x07\u202ename"
        proj = self._tmp_project("ctrl_sanitize")
        (proj / "agents").mkdir()
        actions = [_subagent_layout.Action("skipped", f".claude/agents/{evil}.md", "bad\x1b[0m")]
        text = "\n".join(_subagent_layout.summarize(actions, dry_run=True))
        self.assertNotIn("\x1b", text)
        self.assertNotIn("\x07", text)
        self.assertNotIn("\u202e", text)


class TestSubagentCliIntegration(unittest.TestCase):
    def _tmp_env(self, name: str) -> "tuple[Path, dict[str, str]]":
        base = Path("build/pytest/subagent_cli").resolve() / name
        if base.exists():
            import shutil

            shutil.rmtree(base)
        proj = base / "project"
        home = base / "home"
        codex_home = base / "codex_home"
        proj.mkdir(parents=True)
        home.mkdir()
        codex_home.mkdir()
        return proj, {"HOME": str(home), "CODEX_HOME": str(codex_home)}

    def test_install_update_dry_run_diff_pull_and_clean_end_to_end(self) -> None:
        proj, env = self._tmp_env("e2e_flow")
        (proj / ".gitignore").write_text(".claude\n", encoding="utf-8")

        # 1. Install generates 30 subagents and warns about .claude in .gitignore.
        r_inst = _run_cli("install", str(proj), env=env)
        self.assertEqual(r_inst.returncode, 0, r_inst.stderr)
        self.assertIn(".claude/agents/", r_inst.stdout)
        self.assertIn(".codex/agents/", r_inst.stdout)
        self.assertIn(".gemini/agents/", r_inst.stdout)
        self.assertIn(".gitignore", r_inst.stdout)
        self.assertEqual(len(list((proj / ".claude/agents").glob("*.md"))), 10)
        self.assertEqual(len(list((proj / ".codex/agents").glob("*.toml"))), 10)
        self.assertEqual(len(list((proj / ".gemini/agents").glob("*.md"))), 10)
        self.assertTrue((proj / "agents" / _subagent_layout.MANIFEST_NAME).is_file())

        # 2. Update --dry-run previews exact paths, surfaces .gitignore warning, writes nothing.
        neo_claude = proj / ".claude/agents/neo.md"
        neo_claude.write_text("DRIFTED\n", encoding="utf-8")
        r_dry = _run_cli("update", "--dry-run", str(proj), env=env)
        self.assertEqual(r_dry.returncode, 0, r_dry.stderr)
        self.assertIn(".claude/agents/neo.md", r_dry.stdout)
        self.assertIn(".gitignore", r_dry.stdout)
        self.assertEqual(neo_claude.read_text(encoding="utf-8"), "DRIFTED\n")

        # 3. Diff reports drifted owned subagent and ignores custom user subagent.
        custom = proj / ".claude/agents/my-custom.md"
        custom.write_text("CUSTOM\n", encoding="utf-8")
        r_diff = _run_cli("diff", str(proj), env=env)
        self.assertEqual(r_diff.returncode, 0, r_diff.stderr)
        self.assertIn("Files differ: .claude/agents/neo.md", r_diff.stdout)
        self.assertNotIn("my-custom.md", r_diff.stdout)

        # 4. Pull --dry-run and real pull from peer project updates owned file, ignores custom & symlinks.
        peer, _ = self._tmp_env("e2e_peer")
        self.assertEqual(_run_cli("install", str(peer), env=env).returncode, 0)
        peer_neo = peer / ".claude/agents/neo.md"
        peer_neo.write_text("PEER UPDATED NEO\n", encoding="utf-8")
        (peer / ".claude/agents/my-custom.md").write_text("PEER CUSTOM\n", encoding="utf-8")

        r_pull_dry = _run_cli("pull", "--dry-run", str(peer), cwd=proj, env=env)
        self.assertEqual(r_pull_dry.returncode, 0, r_pull_dry.stderr)
        self.assertIn(".claude/agents/neo.md", r_pull_dry.stdout)
        self.assertNotIn("my-custom.md", r_pull_dry.stdout)
        self.assertEqual(neo_claude.read_text(encoding="utf-8"), "DRIFTED\n")

        r_pull = _run_cli("pull", str(peer), cwd=proj, env=env)
        self.assertEqual(r_pull.returncode, 0, r_pull.stderr)
        self.assertEqual(neo_claude.read_text(encoding="utf-8"), "PEER UPDATED NEO\n")
        self.assertEqual(custom.read_text(encoding="utf-8"), "CUSTOM\n")

        # 5. Clean --yes resets state.md/CHAT.md but leaves generated + custom subagents intact.
        r_clean = _run_cli("clean", "--yes", cwd=proj, env=env)
        self.assertEqual(r_clean.returncode, 0, r_clean.stderr)
        self.assertEqual(len(list((proj / ".claude/agents").glob("*.md"))), 11)
        self.assertEqual(len(list((proj / ".codex/agents").glob("*.toml"))), 10)
        self.assertEqual(len(list((proj / ".gemini/agents").glob("*.md"))), 10)

    def test_diff_notes_missing_manifest_for_pre_sprint5_project(self) -> None:
        proj, env = self._tmp_env("pre_sprint5_diff")
        self.assertEqual(_run_cli("install", str(proj), env=env).returncode, 0)
        (proj / "agents" / _subagent_layout.MANIFEST_NAME).unlink()
        r = _run_cli("diff", str(proj), env=env)
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertIn(".bobp-subagents", r.stdout)

    def test_cli_catches_hostile_symlink_and_exits_1_cleanly(self) -> None:
        proj, env = self._tmp_env("hostile_cli")
        outside = proj.parent / "outside"
        outside.mkdir()
        (proj / ".codex").symlink_to(outside)
        r = _run_cli("install", str(proj), env=env)
        self.assertEqual(r.returncode, 1)
        self.assertNotIn("Traceback", r.stderr)
        self.assertIn(".codex", r.stderr)

    def test_pull_skips_symlinked_src_or_dest_parent(self) -> None:
        proj, env = self._tmp_env("pull_symlink_dest")
        peer, _ = self._tmp_env("pull_symlink_src")
        self.assertEqual(_run_cli("install", str(proj), env=env).returncode, 0)
        self.assertEqual(_run_cli("install", str(peer), env=env).returncode, 0)
        # Replace peer's .claude/agents with a symlink to outside.
        import shutil

        outside = peer.parent / "outside_secret"
        outside.mkdir()
        (outside / "neo.md").write_text("SECRET\n", encoding="utf-8")
        shutil.rmtree(peer / ".claude/agents")
        (peer / ".claude/agents").symlink_to(outside)

        before = (proj / ".claude/agents/neo.md").read_text(encoding="utf-8")
        r = _run_cli("pull", str(peer), cwd=proj, env=env)
        self.assertEqual(r.returncode, 0, r.stderr)
        self.assertEqual((proj / ".claude/agents/neo.md").read_text(encoding="utf-8"), before)

    def test_preflight_refuses_regular_file_at_codex_and_symlinked_gitignore_is_safe(self) -> None:
        proj, env = self._tmp_env("regular_file_codex")
        (proj / ".codex").write_text("", encoding="utf-8")
        r = _run_cli("install", str(proj), env=env)
        self.assertEqual(r.returncode, 1)
        self.assertNotIn("Traceback", r.stderr)
        self.assertIn(".codex", r.stderr)

        proj2, _ = self._tmp_env("symlink_gitignore")
        outside = proj2.parent / "outside_gi"
        outside.write_text(".claude\n", encoding="utf-8")
        (proj2 / ".gitignore").symlink_to(outside)
        self.assertEqual(_subagent_layout.gitignore_hides_subagents(proj2), [])

    def test_repo_committed_subagents_match_packaged_templates(self) -> None:
        repo_root = Path(__file__).resolve().parent.parent
        tmpl = _bob_manage.templates_dir()
        compiled = _subagent_layout.compile_subagents(tmpl)
        for rel, expected in compiled.items():
            actual_path = repo_root / rel
            with self.subTest(path=rel):
                self.assertTrue(actual_path.is_file(), f"missing repo subagent {rel}")
                self.assertFalse(actual_path.is_symlink(), f"{rel} must not be a symlink")
                self.assertEqual(actual_path.read_text(encoding="utf-8"), expected)


